/** Only well-formed user/assistant turns reach the model. */
function sanitize(messages) {
  if (!Array.isArray(messages)) return []
  return messages
    .filter(
      (m) =>
        m &&
        (m.role === 'user' || m.role === 'assistant') &&
        typeof m.content === 'string' &&
        m.content.trim()
    )
    .slice(-MAX_MESSAGES)
    .map((m) => ({ role: m.role, content: m.content.slice(0, 2000) }))
}

exports.handler = async (event) => {
  if (event.httpMethod !== 'POST') {
    return { statusCode: 405, body: 'Method Not Allowed' }
  }

  const apiKey = process.env.ANTHROPIC_API_KEY
  if (!apiKey) {
    console.error('[chat] ANTHROPIC_API_KEY is not configured — falling back to the built-in answers')
    return { statusCode: 503, body: JSON.stringify({ error: 'not configured' }) }
  }

  let messages
  try {
    messages = sanitize(JSON.parse(event.body || '{}').messages)
  } catch {
    return { statusCode: 400, body: JSON.stringify({ error: 'bad request' }) }
  }
  if (!messages.length) {
    return { statusCode: 400, body: JSON.stringify({ error: 'no messages' }) }
  }

  try {
    const res = await fetch('https://api.anthropic.com/v1/messages', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'x-api-key': apiKey,
        'anthropic-version': '2023-06-01',
      },
      body: JSON.stringify({ model: MODEL, max_tokens: MAX_TOKENS, system: SYSTEM, messages }),
    })

    if (!res.ok) {
      console.error(`[chat] Anthropic responded ${res.status}: ${(await res.text()).slice(0, 300)}`)
      return { statusCode: 502, body: JSON.stringify({ error: 'upstream' }) }
    }

    const data = await res.json()
    const text = (data.content || [])
      .filter((block) => block.type === 'text')
      .map((block) => block.text)
      .join('\n')
      .trim()

    return {
      statusCode: 200,
      headers: { 'Content-Type': 'application/json; charset=utf-8' },
      body: JSON.stringify({ text }),
    }
  } catch (err) {
    console.error('[chat] request failed', err)
    return { statusCode: 502, body: JSON.stringify({ error: 'upstream' }) }
  }
}
